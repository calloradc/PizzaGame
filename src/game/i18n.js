export function translate(text, language = "ru", values = {}) {
  let result = language === "en" ? en[text] || text : text;
  if (language === "en" && result === text && text) {
    const patterns = [
      [/^ВОЛНА (\d+)$/, (_, n) => `WAVE ${n}`],
      [/^УРОВЕНЬ (\d+)$/, (_, n) => `LEVEL ${n}`],
      [/^Продолжаем с волны (\d+)$/, (_, n) => `Continuing at wave ${n}`],
      [/^Вкусно сыграно! \+(\d+)$/, (_, n) => `Well played! +${n}`],
      [/^Возвращено (\d+) монет$/, (_, n) => `Refunded: ${n}`],
      [/^Нужно ещё (\d+) монет$/, (_, n) => `Need ${n} more resources`],
      [
        /^Ранняя доставка: \+22 монеты. Враги ещё на пути!$/,
        () => "Early delivery: +22. Enemies are still incoming!",
      ],
      [/^(.+) построена$/, (_, name) => `${en[name] || name} built`],
      [
        /^Рецепт добавлен: (.+)$/,
        (_, name) => `Recipe added: ${en[name] || name}`,
      ],
      [/^(.+) повержен!$/, (_, name) => `${en[name] || name} defeated!`],
      [/^Босс повержен · \+(\d+) монет$/, (_, n) => `Boss defeated · +${n}`],
      [
        /^(.+) ИДЁТ НА КУХНЮ$/,
        (_, name) =>
          `${
            Object.entries(en)
              .find(([key]) => key.toUpperCase() === name)?.[1]
              ?.toUpperCase() || name
          } INCOMING`,
      ],
    ];
    for (const [pattern, replace] of patterns)
      if (pattern.test(text)) {
        result = text.replace(pattern, replace);
        break;
      }
    if (result === text)
      result =
        Object.entries(en)
          .find(([key]) => key.toUpperCase() === text)?.[1]
          ?.toUpperCase() || text;
  }
  for (const [key, value] of Object.entries(values))
    result = result.replaceAll(`{${key}}`, value);
  return result;
}
