export const bossOrder = ["boss", "moldboss", "chiliboss", "general"];
export const bossForWave = (wave) =>
  bossOrder[(Math.floor(wave / 6) - 1) % bossOrder.length];
export function planWave(wave, diff = 0) {
  const count =
    diff === 0
      ? Math.min(44, 10 + Math.floor(wave * 1.5))
      : Math.min(76, 12 + wave * 2 + Math.floor(wave / 6) * 3);
  const queue = [];
  for (let i = 0; i < count; i++) {
    let type = "tomato";
    if (wave >= 2 && i % 3 === 1) type = "olive";
    if (wave >= 3 && i % 5 === 2) type = "mush";
    if (wave >= 4 && i % 8 === 3) type = "healer";
    if (wave >= 5 && i % 7 === 4) type = "pepper";
    if (wave >= 6 && i % 7 === 5) type = "dough";
    if (wave >= 7 && i % 6 === 0) type = "shield";
    if (wave >= 4 && i % 9 === 6) type = "popcorn";
    if (wave >= 8 && i % 10 === 7) type = "onion";
    if (wave >= 10 && i % 12 === 9) type = "mint";
    queue.push({ type, wave, elite: wave >= 9 && i % 11 === 8 });
  }
  if (wave % 6 === 0)
    queue.splice(Math.floor(count * 0.55), 0, {
      type: bossForWave(wave),
      wave,
    });
  return queue;
}
